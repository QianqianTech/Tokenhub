CREATE TABLE IF NOT EXISTS user_sync_devices (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  device_id VARCHAR(80) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  department_id BIGINT UNSIGNED NOT NULL,
  api_key_id BIGINT UNSIGNED NULL,
  device_name VARCHAR(160) NULL,
  platform VARCHAR(80) NULL,
  client_version VARCHAR(80) NULL,
  last_seen_at TIMESTAMP NULL,
  status ENUM('active','disabled') NOT NULL DEFAULT 'active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_sync_devices_device_user (device_id, user_id),
  KEY idx_sync_devices_user (user_id, status),
  KEY idx_sync_devices_api_key (api_key_id),
  CONSTRAINT fk_sync_devices_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_sync_devices_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sync_devices_api_key FOREIGN KEY (api_key_id) REFERENCES api_keys(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS user_sync_records (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  record_id VARCHAR(80) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  department_id BIGINT UNSIGNED NOT NULL,
  api_key_id BIGINT UNSIGNED NULL,
  device_id VARCHAR(80) NULL,
  namespace VARCHAR(120) NOT NULL,
  client_record_id VARCHAR(190) NOT NULL,
  payload_json JSON NOT NULL,
  payload_hash CHAR(64) NOT NULL,
  sync_version BIGINT UNSIGNED NOT NULL,
  client_updated_at TIMESTAMP NULL,
  deleted_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_sync_records_record_id (record_id),
  UNIQUE KEY uq_sync_user_namespace_client_record (user_id, namespace, client_record_id),
  KEY idx_sync_user_version (user_id, sync_version),
  KEY idx_sync_user_updated (user_id, updated_at),
  KEY idx_sync_namespace (user_id, namespace, updated_at),
  KEY idx_sync_records_api_key (api_key_id),
  CONSTRAINT fk_sync_records_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_sync_records_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sync_records_api_key FOREIGN KEY (api_key_id) REFERENCES api_keys(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS user_sync_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  request_id VARCHAR(80) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  department_id BIGINT UNSIGNED NOT NULL,
  api_key_id BIGINT UNSIGNED NULL,
  device_id VARCHAR(80) NULL,
  action VARCHAR(80) NOT NULL,
  namespace VARCHAR(120) NULL,
  record_count INT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('success','failed','conflict') NOT NULL,
  summary JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_sync_events_user (user_id, created_at),
  KEY idx_sync_events_api_key (api_key_id),
  KEY idx_sync_events_action (action, status),
  CONSTRAINT fk_sync_events_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_sync_events_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sync_events_api_key FOREIGN KEY (api_key_id) REFERENCES api_keys(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


<?php
declare(strict_types=1);
require __DIR__ . '/../bootstrap.php';

use TokenHub\Services\Gateway\GatewayRequest;
use TokenHub\Services\Providers\Vendor\VendorAdapter;
use TokenHub\Services\Providers\Vendor\VendorProfiles;
use TokenHub\Services\ProviderModelSyncService;
use TokenHub\Services\RealtimeService;

$route = ['base_url' => 'https://token-plan.maas.qianwenaiapi.com/compatible-mode/v1', 'protocol' => 'openai'];
$request = static fn (string $endpoint, string $capability, string $model, array $payload): GatewayRequest => new GatewayRequest($endpoint, 'openai', $capability, $model, false, ['model' => $model, ...$payload], []);
$imageRoute = ['external_name' => 'wan2.7-image'] + $route;
$imageAdapter = new VendorAdapter(VendorProfiles::specFor($imageRoute, 'image_generation'));
$imageRequest = $request('/v1/images/generations', 'image_generation', 'wan2.7-image', ['prompt' => 'blue square', 'size' => '1024x1024', 'n' => 1]);
$image = $imageAdapter->buildRequest($imageRequest, $imageRoute);
assert_same('https://token-plan.maas.qianwenaiapi.com/api/v1/services/aigc/multimodal-generation/generation', $image['endpoint'], 'Token Plan image generation uses its synchronous native endpoint.');
assert_true(!isset($image['headers']['X-DashScope-Async']), 'Synchronous images must not be submitted as async tasks.');
$normalized = $imageAdapter->normalizeResponse($imageRequest, $imageRoute, ['output' => ['choices' => [['message' => ['content' => [['image' => 'https://media.example/blue.png']]]]]], 'usage' => ['input_tokens' => 28, 'output_tokens' => 2, 'total_tokens' => 30, 'output_image_count' => 1]]);
assert_same(30, $normalized['usage']['total_tokens'], 'Measured image tokens survive vendor normalization.');
assert_same(1, $normalized['vendor_usage']['image_count'], 'Qwen image output_image_count is canonicalized.');
$ttsRoute = ['external_name' => 'qwen-audio-3.0-tts-plus'] + $route;
$ttsAdapter = new VendorAdapter(VendorProfiles::specFor($ttsRoute, 'tts'));
$tts = $ttsAdapter->buildRequest($request('/v1/audio/speech', 'tts', $ttsRoute['external_name'], ['input' => 'hello']), $ttsRoute);
assert_same('longanhuan_v3.6', $tts['json']['input']['voice'], 'Token Plan gets a valid Qwen Audio default voice.');
assert_same(24000, $tts['json']['input']['sample_rate'], 'Speech sample rate is explicit.');
$asrRoute = ['external_name' => 'qwen-audio-3.0-asr-flash'] + $route;
$asrAdapter = new VendorAdapter(VendorProfiles::specFor($asrRoute, 'asr'));
$data = 'data:audio/wav;base64,UklGRg==';
$asrRequest = $request('/v1/audio/transcriptions', 'asr', $asrRoute['external_name'], ['file_url' => $data, 'language' => 'en']);
$asr = $asrAdapter->buildRequest($asrRequest, $asrRoute);
assert_same($image['endpoint'], $asr['endpoint'], 'Qwen Audio ASR uses the native multimodal endpoint, not chat completions.');
assert_same($data, $asr['json']['input']['messages'][0]['content'][0]['input_audio']['data'], 'Audio bytes are forwarded unchanged in input.messages.');
assert_same(['en'], $asr['json']['parameters']['language_hints'], 'The ASR language hint follows the native schema.');
assert_same('wav', $asr['json']['parameters']['format'], 'The native ASR endpoint requires an audio format inferred from uploaded media.');
$transcript = $asrAdapter->normalizeResponse($asrRequest, $asrRoute, ['output' => ['sentence' => ['text' => 'one plus one equals two']], 'usage' => ['duration' => 2]]);
assert_same('one plus one equals two', $transcript['text'], 'Native ASR output is normalized into an OpenAI transcript.');
assert_same(2, $transcript['duration'], 'ASR duration comes from measured upstream usage.');
$video = VendorProfiles::specFor(['external_name' => 'wan3.0-video'] + $route, 'video_generation');
assert_same('async', $video['mode'], 'Wan video has an executable task adapter.');
assert_same('/api/v1/tasks/{id}', $video['poll']['path'], 'Video polling uses the native task endpoint.');
$realtime = new RealtimeService();
assert_same('wss://token-plan.maas.qianwenaiapi.com/api-ws/v1/realtime?model=qwen-audio-3.0-realtime-plus', $realtime->upstreamUrl($route, 'qwen-audio-3.0-realtime-plus'), 'Realtime audio uses the separate native WebSocket path.');
$override = $route + ['default_headers' => ['tokenhub_realtime_url' => 'wss://custom.example/session?model={model}']];
assert_same('wss://custom.example/session?model=chosen', $realtime->upstreamUrl($override, 'chosen'), 'An explicit operator realtime URL keeps precedence.');
$catalog = new ProviderModelSyncService();
assert_same('moderation', $catalog->inferCapability('decision-model-preview'), 'Decision models use the structured classification endpoint.');
assert_same('video_understanding', $catalog->inferCapability('qwen3.8-flash'), 'New Qwen Flash input modalities are recognized.');
assert_same('vision_understanding', $catalog->inferCapability('qwen3.8-max'), 'New Qwen Max vision input is recognized.');
